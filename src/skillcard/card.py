"""Render the score card PNG.

Design rules: restrained, flat, one accent color, watermark is a single
small line at the bottom. The big grade letter is the hero - people
share cards, not numbers.
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

from skillcard.models import EvalResult, grade_color

BG = "#ffffff"
BORDER = "#d0d7de"
TEXT = "#1f2328"
MUTED = "#57606a"
TRACK = "#e5e9ee"

W, H = 680, 620


_FONT_CANDIDATES = [
    "DejaVuSans.ttf",       # Linux / cross-platform
    "Segoe UI",            # Windows
    "Arial",               # Windows fallback
    "Helvetica Neue",      # macOS
    "Helvetica",           # macOS fallback
    "PingFang SC",         # macOS Chinese
    "Microsoft YaHei",     # Windows Chinese
    "Noto Sans CJK SC",    # Linux Chinese
]


def _font(size: int) -> ImageFont.FreeTypeFont:
    for name in _FONT_CANDIDATES:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    # Last resort: default bitmap font.
    try:
        return ImageFont.load_default(size=size)
    except TypeError:  # very old Pillow
        return ImageFont.load_default()


def render_card(result: EvalResult, out_path: str | Path) -> Path:
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)
    accent = grade_color(result.grade)

    f_title = _font(26)
    f_grade = _font(110)
    f_score = _font(22)
    f_dim = _font(18)
    f_small = _font(14)

    # Header (left)
    d.text((40, 38), "Skill Quality Card", font=f_title, fill=TEXT)
    name = result.skill_name or Path(result.path).parent.name
    d.text((40, 76), name, font=f_small, fill=MUTED)

    # Grade hero (right)
    grade_w = d.textlength(result.grade, font=f_grade)
    d.text((W - 40 - grade_w, 28), result.grade, font=f_grade, fill=accent)
    score_txt = f"{result.total_score:.0f} / 100"
    score_w = d.textlength(score_txt, font=f_score)
    d.text((W - 40 - score_w, 150), score_txt, font=f_score, fill=TEXT)

    # Dimension bars
    y = 210
    bar_x, bar_w, bar_h = 250, 300, 14
    for dim in result.dimensions:
        d.text((40, y - 4), dim.label, font=f_dim, fill=TEXT)
        d.rounded_rectangle([bar_x, y, bar_x + bar_w, y + bar_h], radius=7, fill=TRACK)
        if dim.score is not None:
            fill_w = max(bar_h, int(bar_w * dim.score / 100))
            d.rounded_rectangle([bar_x, y, bar_x + fill_w, y + bar_h], radius=7, fill=accent)
            d.text((bar_x + bar_w + 16, y - 5), f"{dim.score:.0f}", font=f_dim, fill=TEXT)
        else:
            d.text((bar_x + bar_w + 16, y - 5), "n/a", font=f_dim, fill=MUTED)
        y += 52

    # Security gate status (not a scored dimension, just a pass/fail marker)
    n_hits = len(result.injection_hits)
    d.text((40, y - 4), "Security", font=f_dim, fill=TEXT)
    if n_hits == 0:
        d.text((bar_x, y - 5), "✓ clean", font=f_dim, fill="#2da44e")
    else:
        msg = f"✗ {n_hits} pattern{'s' if n_hits != 1 else ''} found"
        d.text((bar_x, y - 5), msg, font=f_dim, fill="#cf222e")
    y += 52

    # Divider + footer
    d.line([(40, H - 90), (W - 40, H - 90)], fill=BORDER, width=1)
    d.text((40, H - 76), f"judge: {result.judge_model}", font=f_small, fill=MUTED)
    if result.judge_prompt_hash:
        d.text(
            (40, H - 54),
            f"judge prompt: {result.judge_prompt_hash}  |  eval {result.eval_version}",
            font=f_small,
            fill=MUTED,
        )
    d.text((40, H - 28), "generated by skillcard", font=f_small, fill=BORDER)

    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out, "PNG")
    return out
